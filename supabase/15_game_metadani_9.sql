-- ============================================================
--  ГРА «Метадані файлу» — 9 клас, ГР 4 (уроки 9-10), ПІЛОТНА
--  Куди: Supabase -> SQL Editor -> New query -> вставити ВСЕ -> Run.
--  Безпечно запускати повторно: on conflict (slug) do update.
--
--  ⚠️ ВАЖЛИВО: ця гра ЗАМІНЮЄ автоматичну частину Google Форми
--  (10 закритих питань з 12) для підсумкової ГР 4 9 класу.
--  Питання 11 (2 бали, відкрита письмова відповідь) лишається
--  ОКРЕМО в Classroom і перевіряється вчителем вручну — ГРА ЦЬОГО
--  НЕ РАХУЄ. max_score = 10, а НЕ 12 (саме тому, щоб pct_to_grade
--  на сайті не обрізав максимум нижче 12: сайт рахує % від
--  досяжних у грі 10 балів, решта 2 додаються вчителем вручну
--  при виставленні підсумкового балу).
--
--  Формула фінального балу ГР 4 (застосовувати вручну):
--    фінал = "score" гри (0-10, з CSV-експорту адмінки)
--          + бал за відкрите питання № 11 (0-2, вручну)
--    мінімум 3 за виконану роботу, максимум 12.
--  Деталі — у файлі "Критерії оцінювання — підсумкова ГР 4 і ПР № 2.md".
-- ============================================================

insert into public.games (slug, title, description, max_score)
values (
  'metadani-9',
  '9 клас · Метадані файлу',
  'Що їде разом із файлом .docx і PDF: автор, дати, коментарі, колонтитул. 10 закритих питань з 12 (ще 2 бали — за письмову відповідь окремо в Classroom, вручну) — ГР 4, 9 клас, уроки 9-10',
  10
)
on conflict (slug) do update
  set title       = excluded.title,
      description = excluded.description,
      max_score   = excluded.max_score;

-- ============================================================
--  ПЕРЕВІРКА: тепер у каталозі мусить бути 10 ігор
-- ============================================================
select slug, title, max_score, active
from public.games
order by slug;
