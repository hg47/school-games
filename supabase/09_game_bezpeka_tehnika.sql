--
--  Раунди: 1) реклама-«прискорювач»: познач 4 ознаки обману з 7;
--          2) який тип комп'ютера під задачу (суперкомп'ютер / сервер /
--             персональний / вбудований) — 6 задач;
--          3) що робити МОЖНА, а чого не можна — 4 правильні з 7 (етика);
--          4) що робити при неполадці: сам / засіб Windows / до фахівця — 6 ситуацій;
--          5) «Держава у смартфоні»: що справді доступно — 4 правильні з 7.
--
--  ⚠️ ЦЯ ГРА ОХОПЛЮЄ ДВІ ТЕМИ. Мітки ГР 4 в КТП 8-А стоять на уроках 2, 10, 13
--     (поточні) і 12 (підсумкова). Тому перевіряється матеріал:
--       • уроку 2  (Тема 1) — шифрування, конфіденційність, етика;
--       • уроку 10 (Тема 2) — «прискорювачі», діагностика, добір під задачу;
--       • уроку 12 (Тема 2) — види й застосування комп'ютерів, «Держава у смартфоні».
--
--  ⚠️ У грі НЕМАЄ обчислень — вона перевіряє РІШЕННЯ, а не арифметику.
--     Обчислювальні навички перевіряла гра koduvannya-8 (ГР 1, урок 7).
--
--  ⚠️ Ім'я файлу гри мусить бути bezpeka-tehnika-8.html, бо index.html робить
--     перехід на games/<game_slug>.html.
-- ============================================================

insert into public.games (slug, title, description, max_score)
values (
  'bezpeka-tehnika-8',
  'Безпека й технології',
  'Розпізнавання шахрайської реклами, вибір типу комп''ютера під задачу, етика й безпека цифрової взаємодії, дії при неполадках, державні послуги в смартфоні — ГР 4, 8 клас',
  24
)
on conflict (slug) do update
  set title       = excluded.title,
      description = excluded.description,
      max_score   = excluded.max_score;

