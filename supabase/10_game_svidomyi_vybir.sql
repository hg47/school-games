--  Безпечно запускати повторно (upsert за slug).
--
--  max_score = 26 (4 + 6 + 6 + 4 + 6 правильних дій у 5 раундах) —
--  сервер рахує % = score / max_score, а pct_to_grade() → бал 1–12.
--
--  Раунди: 1) що справді дає хмарний сервіс — познач 4 правильні з 7 (урок 5);
--          2) чим зробити задачу зі звуком: онлайн-сервіс / редактор доріжок —
--             6 задач (урок 8);
--          3) розгалуження в презентації потрібне чи зайве — 6 ситуацій (урок 12);
--          4) керування показом: познач 4 правильні твердження з 7 (урок 13);
--          5) кому цей маршрут показу: виступ 2 хв / дивляться самі /
--             захист перед комісією — 6 рішень (уроки 12–13).
--
--  ⚠️ ЦЯ ГРА ОХОПЛЮЄ ТРИ ТЕМИ. Мітки ГР 3 в КТП 7-А стоять на уроках
--     5, 8, 12, 13 (усі поточні), а урок 16 — єдина ПІДСУМКОВА точка ГР 3
--     за семестр. Тому перевіряється матеріал:
--       • уроку 5  (Тема 1) — хмарні сервіси, синхронізація;
--       • уроку 8  (Тема 2) — вибір інструмента для монтажу звуку;
--       • уроку 12 (Тема 3) — розгалуження: коли потрібне, коли зайве;
--       • уроку 13 (Тема 3) — кнопки дій, користувацький показ, маршрут.
--     ⭐ Клас треба попередити ЗАЗДАЛЕГІДЬ двома фразами: «робота за три теми»
--     ПЛЮС «немає означень і обчислень, тільки рішення». Перша без другої
--     дає паніку.
--
--  ⚠️ У грі НЕМАЄ обчислень і НЕМАЄ означень «за підручником» — вона перевіряє
--     РІШЕННЯ (усвідомлений вибір), як і належить ГР 3.
--
--  ⚠️ Питання побудовані так, щоб на них відповів і той, хто працює
--     в Google Презентаціях: назв кнопок конкретної програми в раундах немає,
