--  ГРА «Графіка: свідомий вибір» — частина Підсумкової роботи ГР 3 (6 клас, урок 21)
--  Куди: Supabase → SQL Editor → New query → вставити ВСЕ → Run.
--  Безпечно запускати повторно (upsert за slug).
--  max_score = 27 (6 + 6 + 5 + 4 + 6 правильних дій у 5 раундах) —
--  сервер рахує % = score / max_score, а pct_to_grade() → бал 1–12.
--  Раунди: 1) растр чи вектор під задачу; 2) чим малювати елемент (Безьє / примітив / копія);
--          3) порядок кроків створення векторного зображення;
--          4) засобом програми чи «на око»; 5) у якому форматі зберігати.
--
--  ⚠️ Це ПЕРША з двох контрольних точок ГР 3 на уроці 21. Друга — власне зображення
--  за рубрикою («Критерії оцінювання ГР 3.md»). Правило зведення двох балів — у тому ж файлі.
-- ============================================================

insert into public.games (slug, title, description, max_score)
values (
  'grafika-6',
  'Графіка: свідомий вибір',
  'Растр чи вектор під задачу, вибір інструмента під елемент, порядок створення, точність засобами програми, формати файлів — ГР 3, 6 клас',
  27
)
on conflict (slug) do update
  set title       = excluded.title,
      description = excluded.description,
      max_score   = excluded.max_score;

-- ПЕРЕВІРКА: має повернути рядок гри з max_score = 27
select slug, title, max_score, active from public.games where slug = 'grafika-6';
